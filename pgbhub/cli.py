"""PGBHub Python CLI — Generate Pydantic models from /schema.json."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from pgbhub.client import PGBHubClient


def main():
    parser = argparse.ArgumentParser(description="PGBHub Python CLI — Schema inspection and Pydantic model codegen")
    parser.add_argument("command", nargs="?", default="pull", choices=["pull", "inspect"], help="Command to run")
    parser.add_argument("--endpoint", default=None, help="PGBHub endpoint (default: PGBHUB_ENDPOINT, or the project address from PGBHUB_PROJECT_ID)")
    parser.add_argument("--key", help="PGBHub API Key")
    parser.add_argument("--db", default=None, help="Target database name (default: the one the key belongs to)")
    parser.add_argument("--out", default="models_pgbhub.py", help="Output python models file")

    args = parser.parse_args()

    client = PGBHubClient(api_key=args.key, endpoint=args.endpoint, database=args.db)

    print(f"📡 Connecting to PGBHub at {client.endpoint}...")
    try:
        schema = client.get_schema()

        if args.command == "inspect":
            import json
            print(json.dumps(schema, indent=2))
            return

        print(f"✨ Generating Pydantic v2 models from schema (v{schema.get('version', '1.0.0')})...")
        code = generate_pydantic_models(schema)

        out_path = Path.cwd() / args.out
        out_path.write_text(code, encoding="utf-8")
        print(f"✅ Successfully generated Pydantic models: {args.out}")
    except Exception as e:
        print(f"❌ Error: {e}", file=sys.stderr)
        sys.exit(1)


def generate_pydantic_models(schema: dict) -> str:
    lines = [
        "# Auto-generated by PGBHub Python CLI (pgbhub pull)",
        "# Do not edit directly. Re-run 'pgbhub pull' to sync latest database changes.",
        "",
        "from __future__ import annotations",
        "from datetime import datetime, date",
        "from typing import Any, Optional",
        "from pydantic import BaseModel, Field",
        "",
        "",
    ]

    for table_key, table in schema.get("tables", {}).items():
        class_name = to_pascal_case(table["name"])
        lines.append(f"class {class_name}(BaseModel):")
        lines.append(f'    """Database table: {table_key}"""')

        columns = table.get("columns", [])
        if not columns:
            lines.append("    pass\n")
            continue

        for col in columns:
            py_type = col.get("type_py", "Any")
            col_name = col["name"]
            nullable = col.get("nullable", False)

            if nullable:
                type_str = f"Optional[{py_type}]"
                default_str = "= None"
            else:
                type_str = py_type
                default_str = ""

            lines.append(f"    {col_name}: {type_str} {default_str}".rstrip())

        lines.append("\n")

    return "\n".join(lines)


def to_pascal_case(text: str) -> str:
    parts = text.replace("-", "_").split("_")
    return "".join(p.capitalize() for p in parts if p)


if __name__ == "__main__":
    main()
